// Takes, from tests/acceptance/490-oracle's port of libieeep1788_elem.rs (inari 9e519ce47c, made there by
// extract-itf1788.mjs from the pinned file), the cases of the functions #505's plots and implicit curves are built from
// (sin, cos, sqr, pown, pow, div, recip), and writes them as JSON on stdout with the file's Apache-2.0 notice:
//
//   node fixtures/subset-itf1788.mjs ../490-oracle/fixtures/itf1788-libieeep1788-elem.json > fixtures/itf1788-plot-functions.json
//
// No case is changed: each keeps its upstream test, line, assert text, expression over x, input interval and tight
// enclosure exactly as the 490-oracle fixture holds them. Generated data; never edited by hand.
import { readFileSync } from 'node:fs';

const TESTS = ['minimal_sin_test', 'minimal_cos_test', 'minimal_sqr_test', 'minimal_pown_test', 'minimal_pow_test', 'minimal_div_test', 'minimal_recip_test'];
const from = JSON.parse(readFileSync(process.argv[2], 'utf8'));
const cases = from.cases.filter((c) => TESTS.includes(c.test));
for (const t of TESTS) if (!cases.some((c) => c.test === t)) throw Error(`no case of ${t}`);
process.stdout.write(`${JSON.stringify({
  source: from.source,
  upstream: from.upstream,
  license: from.license,
  notice: from.notice,
  note: `The cases of ${TESTS.join(', ')} from tests/acceptance/490-oracle/fixtures/itf1788-libieeep1788-elem.json (its cases and dropped counts say what that port left out and why), unchanged. Generated by subset-itf1788.mjs; never edited by hand.`,
  tests: TESTS,
  kept: cases.length,
  cases,
}, null, 1)}\n`);
