// Helpers for #3333's acceptance tests: a temporary folder and HOME per test, a throttle table of that HOME's own
// filled by real holders so it grants no more builds, a tiny cargo workspace, and the lane's reader of a cargo test run:
// the checkout's own `cargoResults`, `crates` and `readRun` of scripts/lanes.mjs. The reader runs in a process of its
// own, so a missing export or a throw reads as an assertion failure here, never as an import error.
import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { existsSync, mkdirSync, mkdtempSync, realpathSync, rmSync, writeFileSync } from 'node:fs';
import { homedir, tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

export const CHECKOUT = realpathSync(fileURLToPath(new URL('../../../', import.meta.url)));
const THROTTLE = join(CHECKOUT, 'scripts/throttle.mjs');
/** A cold build of the fixture takes seconds; a hang still ends. */
export const MINUTES = { timeout: 10 * 60_000 };

/**
 * A folder removed after the test, with a HOME of its own (so the throttle reads a table of its own, inside this test
 * run), and the environment the commands run in: the machine's cargo and rustup, the fixture's own target.
 */
export function sandbox(t) {
  const dir = realpathSync(mkdtempSync(join(tmpdir(), 'deep-3333-')));
  const home = join(dir, 'home');
  mkdirSync(home);
  const env = { ...process.env, HOME: home, CARGO_HOME: process.env.CARGO_HOME ?? join(homedir(), '.cargo'), RUSTUP_HOME: process.env.RUSTUP_HOME ?? join(homedir(), '.rustup') };
  for (const name of ['CARGO_TARGET_DIR', 'CARGO_BUILD_TARGET', 'RUSTFLAGS', 'DEEP_PROOF_VITEST_REPORT', 'DEEP_THROTTLE', 'DEEP_THROTTLE_TABLE', 'DEEP_THROTTLE_READINGS', 'DEEP_THROTTLE_RUN']) delete env[name];
  const box = { dir, home, env, children: [] };
  t.after(() => {
    // Only the processes this test started, by their process group's PID.
    for (const child of box.children) if (child.exitCode === null && child.signalCode === null) try { process.kill(-child.pid, 'SIGKILL'); } catch {}
    rmSync(dir, { recursive: true, force: true });
  });
  return box;
}

/** Starts `argv` in its own process group; `done` resolves to its status and its output, stderr and stdout in one stream. */
function start(argv, { cwd = CHECKOUT, env, box }) {
  const child = spawn('/bin/sh', ['-c', 'exec "$@" 2>&1', 'sh', ...argv], { cwd, env, detached: true, stdio: ['ignore', 'pipe', 'pipe'] });
  box.children.push(child);
  let output = '';
  child.stdout.on('data', (chunk) => { output += chunk; });
  child.stderr.on('data', (chunk) => { output += chunk; });
  const done = new Promise((resolve, reject) => {
    child.on('error', reject);
    child.on('close', (status, signal) => resolve({ status, signal, output }));
  });
  return { child, done };
}

export const run = (argv, options) => start(argv, options).done;

/**
 * Fills the box's own throttle table with real build grants: holders `throttle.mjs build --wait 0 -- <sleep>` start
 * one after another until one is refused, so the table now grants no build. Returns the refused holder's run.
 */
export async function fillBuilds(box) {
  for (let k = 0; k < 16; k++) {
    const ready = join(box.dir, `holder-${k}.ready`);
    const holder = start([process.execPath, THROTTLE, 'build', '--wait', '0', '--', '/bin/sh', '-c', `: > "${ready}"; exec sleep 600`], { env: box.env, box });
    let ended = null;
    holder.done.then((result) => { ended = result; });
    while (!existsSync(ready) && !ended) await new Promise((resolve) => setTimeout(resolve, 50));
    if (ended) {
      assert.equal(ended.status, 3, `a holder the full table refused exits 3:\n${ended.output}`);
      assert.match(ended.output, /^INCONCLUSIVE no grant: no build grant came within 0 min/, `the refused holder says why:\n${ended.output}`);
      return ended;
    }
  }
  assert.fail('the test\'s own throttle table granted 16 builds and never filled');
}

export const PACKAGE = 'fixture-3333';

/**
 * A one-package workspace: a library whose one test passes (`passing`) or doesn't compile (`compile-error`). No
 * dependency, so cargo runs offline and `--locked` holds.
 */
export function workspace(box, kind) {
  const root = join(box.dir, 'workspace');
  const body = kind === 'compile-error' ? '        let two: u32 = "two";\n        assert_eq!(super::two(), two);\n' : '        assert_eq!(super::two(), 2);\n';
  const files = {
    'Cargo.toml': '[workspace]\nmembers = ["fixture"]\nresolver = "2"\n',
    'Cargo.lock': `# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n[[package]]\nname = "${PACKAGE}"\nversion = "0.0.0"\n`,
    'fixture/Cargo.toml': `[package]\nname = "${PACKAGE}"\nversion = "0.0.0"\nedition = "2021"\npublish = false\n\n[lib]\ndoctest = false\n`,
    'fixture/src/lib.rs': `pub fn two() -> u32 {\n    2\n}\n\n#[cfg(test)]\nmod tests {\n    #[test]\n    fn two_is_two() {\n${body}    }\n}\n`,
  };
  for (const [path, text] of Object.entries(files)) {
    mkdirSync(dirname(join(root, path)), { recursive: true });
    writeFileSync(join(root, path), text);
  }
  return root;
}

/** The lane's cargo test command (`unit` in scripts/lanes.mjs), run whole on the fixture. */
export const CARGO_TEST = ['cargo', 'test', '--workspace', '--locked', '--no-fail-fast'];

/** The lane's cargo test command through the throttle as a lane runs it (runLanes), but with a wait of 0 minutes. */
export const throttled = (command) => [process.execPath, THROTTLE, 'build', '--wait', '0', '--', ...command];

// cargoResults and crates are what the lane reads a cargo test run with (testsOf), and readRun how it reads the run.
const READER = `import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';
const [checkout, cwd, log, status] = process.argv.slice(2);
const { cargoResults, crates, readRun } = await import(pathToFileURL(join(checkout, 'scripts/lanes.mjs')).href);
const results = cargoResults(readFileSync(log, 'utf8'), Number(status), crates(cwd));
console.log(JSON.stringify({ results, run: readRun(results, Number(status), cwd, []) }));
`;

/** What the checkout's lanes.mjs reads of a cargo test run's output and status, for the workspace at `cwd`. */
export async function read(box, cwd, output, status) {
  const log = join(box.dir, `run-${box.children.length}.log`), reader = join(box.dir, 'reader.mjs');
  // The lane reads its log trimmed (runLanes).
  writeFileSync(log, output.trim());
  writeFileSync(reader, READER);
  const ran = await run([process.execPath, reader, CHECKOUT, cwd, log, String(status)], { cwd, env: box.env, box });
  assert.equal(ran.status, 0, `scripts/lanes.mjs's cargoResults, crates and readRun read the run:\n${ran.output}`);
  return JSON.parse(ran.output.trim().split('\n').at(-1));
}

/** One cargo test run through the throttle on a fixture, read as the lane reads it; `full` fills the table first. */
export async function laneRun(t, { kind, full }) {
  const box = sandbox(t);
  const root = workspace(box, kind);
  if (full) await fillBuilds(box);
  const ran = await run(throttled(CARGO_TEST), { cwd: root, env: box.env, box });
  const { results, run: reading } = await read(box, root, ran.output, ran.status ?? 1);
  const all = `$ throttle.mjs build --wait 0 -- ${CARGO_TEST.join(' ')}  (exit ${ran.status})\n${ran.output.trim()}\n--- cargoResults\n${JSON.stringify(results, null, 1)}\n--- readRun\n${JSON.stringify(reading, null, 1)}`;
  return { ran, results, reading, root, all };
}
