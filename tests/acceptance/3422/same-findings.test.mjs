// #3422's second criterion: the ratchet's findings before and after are the same paths with the same reasons. Before is
// the ratchet as the merge base of HEAD with origin/main holds it, read from git; after is this checkout's, through the
// lint lane's command. Both run over one tree: this checkout ("on main"), and scratch repositories planted with each
// kind of finding the ratchet has, so the comparison holds however few findings this checkout has (README: Before and
// after). A reason is a finding's line; the Fix line under it is what #3422 rewords, and is no part of it. A finding
// that appears, goes or changes its reason fails, naming its path.
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import test from 'node:test';
import { CEILINGS, SAME, SCRIPT, assertSameFindings, baseScript, findings, git, json, put, ratchet, ratchetBefore, root, rust, scratch, show } from './helpers.mjs';

test(`${SAME} on this checkout the ratchet's findings are the same paths with the same reasons as the merge base's ratchet's, and git status is unchanged`, (t) => {
  const status = () => git(root, 'status', '--porcelain=v1', '--untracked-files=all');
  const held = status();
  const before = ratchetBefore(t);
  const after = ratchet(root);
  assert.equal(status(), held, 'running the two ratchets changed git status in this checkout');
  assertSameFindings(before, after, 'on this checkout');
});

/** Both ratchets over one scratch repository: this checkout's, as the copy of scripts/ holds it, then the merge base's
 * written in its place. scripts/ is hidden from git's listing there, so the swap changes nothing either one judges. */
function both(cwd, base) {
  const after = ratchet(cwd);
  put(cwd, SCRIPT, base.text);
  const before = ratchet(cwd);
  put(cwd, SCRIPT, readFileSync(join(root, SCRIPT)));
  return { before, after };
}

const AT = 'crates/fixture/src/at.rs'; // at its ceiling: no finding
const OVER = 'crates/fixture/src/over.rs'; // a line over its ceiling
const SHRUNK = 'crates/fixture/src/shrunk.rs'; // under its ceiling, still over 1,500
const SMALL = 'crates/fixture/src/small.rs'; // at most 1,500 lines, its entry kept
const RAISED = 'crates/fixture/src/raised.rs'; // grown, its ceiling raised to match
const NEW = 'crates/fixture/src/new.rs'; // new over 1,500 lines, no ceiling
const GENERATED = 'crates/fixture/src/generated.rs'; // generated, given a ceiling
const GONE = 'crates/fixture/src/gone.rs'; // a ceiling for a file the work tree doesn't hold
const KINDS = [OVER, SHRUNK, SMALL, RAISED, NEW, GENERATED, GONE];

test(`${SAME} in a scratch repository planted with each kind of finding, the ratchet's findings are the same paths with the same reasons as the merge base's ratchet's; with none planted both pass alike`, (t) => {
  const base = baseScript();
  const held = { [AT]: 1600, [OVER]: 1600, [SHRUNK]: 1600, [SMALL]: 1600, [RAISED]: 1600 };
  const cwd = scratch(t, { ...Object.fromEntries(Object.keys(held).map((path) => [path, rust(1600)])), [GENERATED]: `// @generated by the fixture\n${rust(1600)}`, [CEILINGS]: json(held) });

  const clean = both(cwd, base);
  assert.deepEqual(findings(clean.before), [], `the merge base's ratchet finds something in the scratch repository before anything is planted\n${show(clean.before)}`);
  assertSameFindings(clean.before, clean.after, 'in the scratch repository with nothing planted');

  put(cwd, OVER, rust(1601));
  put(cwd, SHRUNK, rust(1550));
  put(cwd, SMALL, rust(1400));
  put(cwd, RAISED, rust(1610));
  put(cwd, NEW, rust(1501));
  put(cwd, CEILINGS, json({ ...held, [RAISED]: 1610, [GENERATED]: 1601, [GONE]: 1700 }));
  const planted = both(cwd, base);
  // The comparison is over something only when the merge base's ratchet names each planted path once, and no other.
  assert.deepEqual(findings(planted.before).map(({ path }) => path).sort(), [...KINDS].sort(), `the merge base's ratchet doesn't name each planted path once, so the fixture no longer covers each kind of finding\n${show(planted.before)}`);
  assertSameFindings(planted.before, planted.after, 'in the scratch repository planted with each kind of finding');
});

test(`${SAME} in a scratch repository whose ceilings file can't be read, the ratchet's finding is the same path with the same reason as the merge base's ratchet's`, (t) => {
  const base = baseScript();
  const cwd = scratch(t, { [AT]: rust(1600), [CEILINGS]: json({ [AT]: 1600 }) });
  put(cwd, CEILINGS, '{ "crates/fixture/src/at.rs": 1600,\n');
  const { before, after } = both(cwd, base);
  assert.deepEqual(findings(before).map(({ path }) => path), [CEILINGS], `the merge base's ratchet doesn't name ${CEILINGS} alone when it can't be read\n${show(before)}`);
  assertSameFindings(before, after, "in the scratch repository whose ceilings file can't be read");
});
