// Tasks read from the transcript archive (#112), and the 5-hour window read from a run's stream: each test failed on
// the program it names.
import { execFileSync } from 'node:child_process';
import { mkdirSync, mkdtempSync, realpathSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { basename, join } from 'node:path';
import { afterEach, expect, it } from 'vitest';
import { openEvidenceStore } from '@deepbuild/evidence';
import { openRecord, openRecordReader, type Connection } from '@deepbuild/record';
import { archivedTasks } from '../src/index.js';
import { windowOf } from '../src/launcher.js';

const roots: string[] = [];
afterEach(() => { for (const r of roots.splice(0)) rmSync(r, { recursive: true, force: true }); });
const T0 = Date.UTC(2026, 9, 5, 9, 0, 0);
const HOUR = 3_600_000;
let n = 0;
const ulid = (): string => `01K74FX2B4D6F8H0K2M4P6R${String(n++).padStart(3, '0')}`;
const you: Connection = { writer: 'app', actor: 'you', scope: 'you' };

it('reads each session\'s first prompt you typed, at the commit its branch was at then, and finds a removed worktree\'s session in its checkout', async () => {
  // Failed on a reader that took the session's first user entry (a command's caveat), one that took the branch's
  // newest commit, one that skipped every session whose worktree was removed, and one that read a replay's own session
  // as a new task.
  const box = realpathSync(mkdtempSync(join(tmpdir(), 'dce-archive-')));
  roots.push(box);
  const repo = join(box, 'shop');
  mkdirSync(repo);
  const git = (date: number, ...args: string[]) => execFileSync('git', ['-c', 'user.name=Dev', '-c', 'user.email=dev@shop.test', ...args], {
    cwd: repo, encoding: 'utf8', env: { ...process.env, GIT_CONFIG_GLOBAL: '/dev/null', GIT_CONFIG_NOSYSTEM: '1', GIT_AUTHOR_DATE: new Date(date).toISOString(), GIT_COMMITTER_DATE: new Date(date).toISOString() },
  }).trim();
  git(T0, 'init', '-q', '-b', 'main');
  const commits = [0, 2, 4].map((h, i) => {
    writeFileSync(join(repo, 'cart.js'), `// version ${i}\n`);
    git(T0 + h * HOUR, 'add', '-A');
    git(T0 + h * HOUR, 'commit', '-q', '-m', `version ${i}`);
    return git(T0, 'rev-parse', 'HEAD');
  });

  const store = await openEvidenceStore({ root: join(box, 'evidence'), now: () => T0 });
  const record = await openRecord({ path: join(box, 'ledger.db'), now: () => T0, evidence: store });
  const archive = async (lines: object[], start?: { agent: string }): Promise<string> => {
    const id = ulid();
    if (start) await record.append({ writer: 'hook', actor: 'you', scope: 'you', session: id, project: 'shop' }, { v: 1, id: ulid(), kind: 'session.start', ts: T0, data: { agent: start.agent, worktree: repo, branch: 'main', thread: id } });
    const put = await store.connect({ role: 'deepbuild', via: 'capture' }).put({ bytes: new Uint8Array(Buffer.from(lines.map((l) => JSON.stringify(l)).join('\n'))), kind: 'transcript', source: 'claude-code', redaction: 'complete', license: { name: 'own', allows: [] } });
    if (put.status !== 'stored') throw Error('not stored');
    await record.append(you, { v: 1, id: ulid(), kind: 'transcript.archived', ts: T0, data: { session: `session:${id}`, evidence: put.evidence.sha256 } });
    return id;
  };
  const at = (h: number) => new Date(T0 + h * HOUR).toISOString();
  const user = (uuid: string, content: unknown, h: number, cwd: string, more: object = {}) => ({ type: 'user', uuid, timestamp: at(h), cwd, gitBranch: 'main', message: { role: 'user', content }, ...more });
  const here = await archive([
    user('u1', 'Caveat: the messages below were generated by the user while running local commands.', 3, repo, { isMeta: true }),
    user('u2', '<command-name>/model</command-name>', 3, repo),
    { type: 'assistant', uuid: 'a1', timestamp: at(3), message: { role: 'assistant', content: [{ type: 'tool_use', id: 't1', name: 'Read', input: {} }] } },
    user('u3', [{ type: 'tool_result', tool_use_id: 't1', content: 'file text' }], 3, repo),
    user('u4', 'Make the cart total count each item\'s qty.', 3, repo),
    user('u5', 'And add a test.', 3.5, repo),
  ]);
  const gone = await archive([user('g1', 'Clamp the discount at 100 percent.', 1, join(box, 'claude-worktrees', basename(repo), 'old-worktree'))]);
  const elsewhere = await archive([user('e1', 'Fix the footer.', 1, join(box, 'claude-worktrees', 'blog', 'x'))]);
  const codex = await archive([user('c1', 'Fix the header.', 1, repo)], { agent: 'codex' });
  // A replay's agent, run later with your hooks, opens its session in the task's own words.
  const replayed = await archive([user('r1', 'Make the cart total count each item\'s qty.', 5, join(box, 'work', 'a1b2c3', basename(repo)))]);
  await record.close();

  const reader = openRecordReader({ path: join(box, 'ledger.db'), evidence: store });
  try {
    const { tasks, skipped } = await archivedTasks(reader, (sha) => store.read(sha), repo);
    expect(tasks).toEqual([
      { id: `session:${gone}#g1`, at: T0 + HOUR, repo, commit: commits[0], prompt: 'Clamp the discount at 100 percent.' },
      { id: `session:${here}#u4`, at: T0 + 3 * HOUR, repo, commit: commits[1], prompt: 'Make the cart total count each item\'s qty.' },
    ]);
    expect(skipped.map((s) => s.session).sort()).toEqual([`session:${elsewhere}`, `session:${codex}`, `session:${replayed}`].sort());
    const without = await archivedTasks(reader, (sha) => store.read(sha));
    expect(without.tasks.map((t) => t.id)).toEqual([`session:${here}#u4`]);
  } finally {
    reader.close();
  }
}, 60_000);

it("reads the 5-hour window only from a run that reports it, never another limit's utilization", () => {
  // Failed on a reader that took the last rate-limit event's utilization whatever limit it named.
  const event = (rateLimitType: string, utilization: number, resetsAt = 1_793_491_200) => ({ type: 'rate_limit_event', rate_limit_info: { status: 'allowed', rateLimitType, utilization, resetsAt } });
  expect(windowOf([event('five_hour', 0.31), { type: 'result' }, event('five_hour', 0.42, 1_793_500_000)])).toEqual({ used: 0.42, resets: 1_793_500_000 });
  expect(windowOf([event('five_hour', 0.31), event('overage', 0.77)])).toEqual({ used: 0.31, resets: 1_793_491_200 });
  expect(windowOf([event('overage', 0.77), event('seven_day', 0.5)])).toBeUndefined();
});
